MAX_EXACT_COUNT = 2**53 - 1  # The output page reads counts as JavaScript numbers.
FILE_CITATION = re.compile(r"([^:\r\n]+):([+\-]?\d[^\r\n]*)")
LINE_RANGE = re.compile(r"([0-9]+)(?:[-–]([0-9]+))?")


def require_text(value, field):
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{field} must be nonempty text")


def validate_location(record, key, field):
    if key not in record:
        raise ValueError(f"{field}.{key} must be a location or null")
    if record[key] is not None:
        require_text(record[key], f"{field}.{key}")


def require_id(value, field):
    if not isinstance(value, str) or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", value):
        raise ValueError(f"{field} needs a lowercase id, with hyphens between words")


def records(items, field):
    if not isinstance(items, list):
        raise ValueError(f"{field} must be a list")
    indexed = {}
    for item in items:
        identifier = item.get("id") if isinstance(item, dict) else None
        require_id(identifier, f"Each entry in {field}")
        if identifier in indexed:
            raise ValueError(f"Duplicate id '{identifier}' in {field}")
        indexed[identifier] = item
    return indexed


def require_reference(value, items, field):
    if not isinstance(value, str) or value not in items:
        raise ValueError(f"{field} refers to an unknown id: {value!r}")


def reference_list(values, items, field, *, allow_repeats=False):
    if not isinstance(values, list):
        raise ValueError(f"{field} must be a list of ids")
    included = set()
    for value in values:
        require_reference(value, items, field)
        if not allow_repeats and value in included:
            raise ValueError(f"{field} repeats '{value}'")
        included.add(value)
    return included


def validate_source_links(record, key, sources, field):
    if key in record and not reference_list(record[key], sources, f"{field}.{key}"):
        raise ValueError(f"{field}.{key} needs at least one source")


def validate_handoff(handoff, origin, destination, field):
    if not isinstance(handoff, dict):
        raise ValueError(f"{field} must be an object")
    if not origin.get("actor") or not destination.get("actor"):
        raise ValueError(f"{field} requires an actor on both steps")
    for key in ("work", "entry", "acknowledgment"):
        require_text(handoff.get(key), f"{field}.{key}")


def validate_cohort(group, sources, field):
    if not isinstance(group, dict):
        raise ValueError(f"{field} must be an object")
    for key in ("cohort", "period", "window", "unit"):
        require_text(group.get(key), f"{field}.{key}")
    if group.get("basis") not in ("observed", "fixture"):
        raise ValueError(f"{field}.basis must be observed or fixture")
    require_reference(group.get("source"), sources, f"{field}.source")


def validate_measurements(measurements, choices, sources, field):
    if not isinstance(measurements, list):
        raise ValueError(f"{field} must be a list")
    for index, group in enumerate(measurements):
        name = f"{field}[{index}]"
        validate_cohort(group, sources, name)
        eligible = group.get("eligible")
        if type(eligible) is not int or not 0 < eligible <= MAX_EXACT_COUNT:
            raise ValueError(f"{name}.eligible must be a positive integer at most {MAX_EXACT_COUNT}")
        counts = group.get("counts")
        if not isinstance(counts, dict):
            raise ValueError(f"{name}.counts must be an object keyed by choice id")
        for choice, count in counts.items():
            require_reference(choice, choices, f"{name}.counts")
            if type(count) is not int or not 0 <= count <= eligible:
                raise ValueError(f"{name}.counts.{choice} must be an integer from 0 through eligible")
        if sum(counts.values()) > eligible:
            raise ValueError(f"{name}.counts exceed the eligible denominator")


def validate_outcomes(outcomes, steps, sources):
    if not isinstance(outcomes, list):
        raise ValueError("outcomes must be a list")
    for index, group in enumerate(outcomes):
        field = f"outcomes[{index}]"
        validate_cohort(group, sources, field)
        metrics = group.get("metrics")
        if not isinstance(metrics, list) or not metrics:
            raise ValueError(f"{field}.metrics needs at least one measured outcome")
        for metric_index, metric in enumerate(metrics):
            name = f"{field}.metrics[{metric_index}]"
            if not isinstance(metric, dict):
                raise ValueError(f"{name} must be an object")
            kind = metric.get("kind")
            if kind not in ("completion", "waiting", "rework", "recovery"):
                raise ValueError(f"{name}.kind must be completion, waiting, rework or recovery")
            require_text(metric.get("definition"), f"{name}.definition")
            reference_list(metric.get("steps", []), steps, f"{name}.steps")
            measured = metric.get("measured")
            if type(measured) is not int or not 0 < measured <= MAX_EXACT_COUNT:
                raise ValueError(f"{name}.measured must be a positive integer at most {MAX_EXACT_COUNT}")
            if kind != "waiting" or "eligible" in metric:
                eligible = metric.get("eligible")
                if type(eligible) is not int or not measured <= eligible <= MAX_EXACT_COUNT:
                    raise ValueError(f"{name}.eligible must be an integer from measured through {MAX_EXACT_COUNT}")
            if kind == "waiting":
                if metric.get("statistic") not in ("median", "mean"):
                    raise ValueError(f"{name}.statistic must be median or mean")
                seconds = metric.get("seconds")
                if type(seconds) not in (int, float) or not 0 <= seconds <= MAX_EXACT_COUNT:
                    raise ValueError(f"{name}.seconds must be a finite nonnegative duration at most {MAX_EXACT_COUNT}")
            else:
                count = metric.get("count")
                if type(count) is not int or not 0 <= count <= measured:
                    raise ValueError(f"{name}.count must be an integer from 0 through measured")


def validate_scenarios(scenarios, edges):
    if not isinstance(scenarios, list):
        raise ValueError("scenarios must be a list")
    affected = set()
    for index, scenario in enumerate(scenarios):
        field = f"scenarios[{index}]"
        if not isinstance(scenario, dict):
            raise ValueError(f"{field} must be an object")
        require_text(scenario.get("label"), f"{field}.label")
        checkpoints = scenario.get("steps")
        is_path = scenario.get("path", False)
        if type(is_path) is not bool:
            raise ValueError(f"{field}.path must be a boolean")
        included = reference_list(checkpoints, edges, f"{field}.steps", allow_repeats=is_path)
        if is_path:
            if len(checkpoints) < 2:
                raise ValueError(f"{field}.path needs at least two connected checkpoints")
            for origin, destination in zip(checkpoints, checkpoints[1:]):
                if destination not in edges[origin]:
                    raise ValueError(f"{field}.steps has no transition from '{origin}' to '{destination}'")
        gaps = scenario.get("gaps", [])
        if not isinstance(gaps, list):
            raise ValueError(f"{field}.gaps must be a list")
        if not included and not gaps:
            raise ValueError(f"{field} needs a mapped step or evidence gap")
        for gap_index, gap in enumerate(gaps):
            gap_field = f"{field}.gaps[{gap_index}]"
            if not isinstance(gap, dict):
                raise ValueError(f"{gap_field} must be an object")
            for key in ("question", "impact", "check"):
                require_text(gap.get(key), f"{gap_field}.{key}")
            if "steps" in gap:
                if "step" in gap:
                    raise ValueError(f"{gap_field} must use either step or steps")
                anchors = reference_list(gap["steps"], edges, f"{gap_field}.steps")
                if not anchors:
                    raise ValueError(f"{gap_field}.steps needs at least one checkpoint")
                if not anchors <= included:
                    raise ValueError(f"{gap_field}.steps must all be listed in {field}.steps")
                affected.update(anchors)
            if "step" in gap:
                require_reference(gap["step"], edges, f"{gap_field}.step")
                if gap["step"] not in included:
                    raise ValueError(f"{gap_field}.step must be listed in {field}.steps")
                affected.add(gap["step"])
    return affected


def validate_record_routes(routes, steps, start):
    record_entries = {}
    for origin, destination, creates, existing in routes:
        if creates is not None and existing is not None:
            raise ValueError(f"{origin} -> {destination} cannot both create and continue on an existing record")
        record = creates or existing
        if record is None:
            continue
        target = steps[destination]
        record_kind = "new" if creates is not None else "existing"
        creates_start = creates is not None and destination == start
        if creates_start or steps[origin].get("record") == record or target.get("record") != record:
            raise ValueError(f"{origin} -> {destination} needs a separate checkpoint on the {record_kind} record '{record}'")
        if target.get("actor") and not target.get("actorSources"):
            raise ValueError(f"steps.{destination}.actorSources must support the actor on the {record_kind} record")
        record_entries[destination] = record

    for origin, destination, creates, existing in routes:
        if (destination in record_entries and creates is None and existing is None
                and steps[origin].get("record") != record_entries[destination]):
            raise ValueError(f"{origin} -> {destination} crosses into '{record_entries[destination]}' without a record transition")


def validate_comparisons(comparisons, steps, sources):
    if not isinstance(comparisons, list):
        raise ValueError("comparisons must be a list")
    for index, comparison in enumerate(comparisons):
        field = f"comparisons[{index}]"
        if not isinstance(comparison, dict):
            raise ValueError(f"{field} must be an object")
        for key in ("question", "goal", "check", "decisionRule"):
            require_text(comparison.get(key), f"{field}.{key}")
        options = comparison.get("options")
        if not isinstance(options, list) or len(options) < 2:
            raise ValueError(f"{field}.options needs at least two options")
        for option_index, option in enumerate(options):
            name = f"{field}.options[{option_index}]"
            if not isinstance(option, dict):
                raise ValueError(f"{name} must be an object")
            kind = option.get("kind")
            if kind not in ("baseline", "proposed"):
                raise ValueError(f"{name}.kind must be baseline or proposed")
            for key in ("label", "change", "effect", "tradeoff", "support"):
                require_text(option.get(key), f"{name}.{key}")
            if "openQuestion" in option:
                require_text(option["openQuestion"], f"{name}.openQuestion")
            if not reference_list(option.get("steps"), steps, f"{name}.steps"):
                raise ValueError(f"{name}.steps needs at least one checkpoint")
            evidence = reference_list(option.get("sources", []), sources, f"{name}.sources")
            if kind == "baseline" and not evidence:
                raise ValueError(f"{name}.sources needs at least one supporting source for a baseline")


def validate(journey):
    version = journey.get("version") if isinstance(journey, dict) else None
    if type(version) is not int or version not in (1, 2):
        raise ValueError("Expected an object with version 1 or 2")
    for key in ("title", "goal", "role", "entry", "success", "coverage"):
        require_text(journey.get(key), key)

    people = records(journey.get("people", []), "people")
    for identifier, person in people.items():
        for key in ("label", "responsibility"):
            require_text(person.get(key), f"people.{identifier}.{key}")

    sources = records(journey.get("sources"), "sources")
    for identifier, source in sources.items():
        for key in ("label", "location", "note"):
            require_text(source.get(key), f"sources.{identifier}.{key}")

    steps = records(journey.get("steps"), "steps")
    if "gaps" in journey or any("gaps" in step for step in steps.values()):
        raise ValueError("Nest evidence gaps in scenarios[].gaps so the map can display them")
    start = journey.get("start")
    require_reference(start, steps, "start")
    validate_comparisons(journey.get("comparisons", []), steps, sources)
    validate_outcomes(journey.get("outcomes", []), steps, sources)
    edges = {}
    record_routes = []
    for identifier, step in steps.items():
        field = f"steps.{identifier}"
        if "record" in step:
            require_text(step["record"], f"{field}.record")
        if "continuationUnknown" in step and type(step["continuationUnknown"]) is not bool:
            raise ValueError(f"{field}.continuationUnknown must be a boolean")
        if "actor" in step:
            require_reference(step["actor"], people, f"{field}.actor")
        if "actorSources" in step and "actor" not in step:
            raise ValueError(f"{field}.actorSources requires a known actor")
        validate_source_links(step, "actorSources", sources, field)
        if "authority" in step:
            require_text(step["authority"], f"{field}.authority")
        if "assignments" in step:
            assignments = step["assignments"]
            if not step.get("actor"):
                raise ValueError(f"{field}.assignments requires an actor who assigns the work")
            if not isinstance(assignments, list) or not assignments:
                raise ValueError(f"{field}.assignments must be a nonempty list")
            for index, assignment in enumerate(assignments):
                name = f"{field}.assignments[{index}]"
                if not isinstance(assignment, dict):
                    raise ValueError(f"{name} must be an object")
                require_reference(assignment.get("role"), people, f"{name}.role")
                require_text(assignment.get("work"), f"{name}.work")
        for key in ("title", "cue", "expectation", "action", "result", "continuation", "basis"):
            require_text(step.get(key), f"{field}.{key}")
        if version == 1:
            require_text(step.get("surface"), f"{field}.surface")
        else:
            if "surface" in step:
                raise ValueError(f"{field}.surface belongs to version 1. Use statusLocation and actionLocation.")
            for key in ("statusLocation", "actionLocation"):
                validate_location(step, key, field)
        if step["basis"] not in BASIS:
            raise ValueError(f"{field}.basis must be one of {', '.join(sorted(BASIS))}")
        refs = step.get("sources")
        if not isinstance(refs, list) or (not refs and step["basis"] not in {"proposed", "unknown"}):
            raise ValueError(f"{field}.sources must list supporting source ids for this evidence basis")
        for ref in refs:
            require_reference(ref, sources, f"{field}.sources")

        if "next" not in step:
            raise ValueError(f"{field}.next must be a step id or null")
        next_id = step["next"]
        if next_id is not None:
            require_reference(next_id, steps, f"{field}.next")
        elif any(key in step for key in ("nextLabel", "nextCondition", "nextHandoff", "nextSources",
                                        "nextCreates", "nextExistingRecord")):
            raise ValueError(f"{field} needs a next step to describe its continuation")
        validate_source_links(step, "nextSources", sources, field)
        for key in ("nextCreates", "nextExistingRecord"):
            if key in step and "nextSources" not in step:
                raise ValueError(f"{field}.{key} needs transition evidence in nextSources")
        for key in ("nextLabel", "nextCondition", "nextCreates", "nextExistingRecord"):
            if key in step:
                require_text(step[key], f"{field}.{key}")
        if next_id is not None:
            record_routes.append((identifier, next_id, step.get("nextCreates"), step.get("nextExistingRecord")))
        if "nextHandoff" in step:
            validate_handoff(step["nextHandoff"], step, steps[next_id], f"{field}.nextHandoff")
        targets = [next_id] if next_id is not None else []
        choices = {"next"} if next_id is not None else set()
        branches = step.get("branches", [])
        if not isinstance(branches, list):
            raise ValueError(f"{field}.branches must be a list")
        for index, branch in enumerate(branches):
            branch_field = f"{field}.branches[{index}]"
            if not isinstance(branch, dict):
                raise ValueError(f"{branch_field} must be an object")
            require_text(branch.get("label"), f"{branch_field}.label")
            require_reference(branch.get("to"), steps, f"{branch_field}.to")
            if "id" in branch:
                choice = branch["id"]
                require_id(choice, f"{branch_field}.id")
                if choice == "next" or choice in choices:
                    raise ValueError(f"{branch_field}.id '{choice}' is reserved or duplicated")
                choices.add(choice)
            if "condition" in branch:
                require_text(branch["condition"], f"{branch_field}.condition")
            for key in ("creates", "existingRecord"):
                if key in branch:
                    require_text(branch[key], f"{branch_field}.{key}")
                    if "sources" not in branch:
                        raise ValueError(f"{branch_field}.{key} needs transition evidence in sources")
            validate_source_links(branch, "sources", sources, branch_field)
            if version == 2 and "actionLocation" in branch:
                validate_location(branch, "actionLocation", branch_field)
            if "handoff" in branch:
                validate_handoff(branch["handoff"], step, steps[branch["to"]], f"{branch_field}.handoff")
            targets.append(branch["to"])
            record_routes.append((identifier, branch["to"], branch.get("creates"), branch.get("existingRecord")))
        validate_measurements(step.get("measurements", []), choices, sources, f"{field}.measurements")
        edges[identifier] = targets

    validate_record_routes(record_routes, steps, start)
    gaps = validate_scenarios(journey.get("scenarios", []), edges)
    for identifier, step in steps.items():
        if step.get("continuationUnknown") and (edges[identifier] or identifier not in gaps):
            raise ValueError(f"steps.{identifier}.continuationUnknown requires a local evidence gap and no outgoing routes")

    primary = set()
    cursor = start
    while cursor is not None:
        if cursor in primary:
            raise ValueError(f"Primary path loops at '{cursor}'. Use a branch for a retry.")
        primary.add(cursor)
        cursor = steps[cursor]["next"]

    seen = set()
    pending = [start]
    while pending:
        identifier = pending.pop()
        if identifier not in seen:
            seen.add(identifier)
            pending.extend(edges[identifier])
    if missing := steps.keys() - seen:
        raise ValueError(f"Steps unreachable from start: {', '.join(sorted(missing))}")


def read_journey(record):
    journey = json.loads(record.read_text(encoding="utf-8-sig"))
    validate(journey)
    return journey


def step_routes(step):
    if step["next"] is not None:
        yield {
            "label": step.get("nextLabel", "Continue"),
            "to": step["next"],
            "condition": step.get("nextCondition"),
            "sources": step.get("nextSources", []),
            "creates": step.get("nextCreates"),
            "existingRecord": step.get("nextExistingRecord"),
            "handoff": "nextHandoff" in step,
        }
    for branch in step.get("branches", []):
        yield {**branch, "handoff": "handoff" in branch}


def outline_expectations(item, identifiers, fields, field):
    require_text(item.get("source"), f"{field}.source")
    if extra := item.keys() - set(identifiers) - fields.keys() - {"source"}:
        raise ValueError(f"{field} has unknown properties: {', '.join(sorted(extra))}")
    expected = {key: item[key] for key in fields if key in item}
    for key, value in expected.items():
        if fields[key] is bool:
            if type(value) is not bool:
                raise ValueError(f"{field}.{key} must be a boolean")
        elif fields[key] is list:
            if not isinstance(value, list):
                raise ValueError(f"{field}.{key} must be a list of role IDs")
            for role in value:
                require_id(role, f"{field}.{key}")
            if len(value) != len(set(value)):
                raise ValueError(f"{field}.{key} repeats a role")
            expected[key] = sorted(value)
        elif value is not None:
            check = require_id if key == "actor" else require_text
            check(value, f"{field}.{key}")
    return expected


def matches_outline_route(route, destination, expected):
    return route["to"] == destination and all(route.get(key) == value for key, value in expected.items())


def boundary_checkpoints(steps):
    required = set()
    for origin, step in steps.items():
        actor = step.get("actor")
        for route in step_routes(step):
            destination = route["to"]
            receiving_actor = steps[destination].get("actor")
            if route.get("creates") or route.get("existingRecord"):
                required.update((origin, destination))
            elif actor and receiving_actor and actor != receiving_actor:
                required.add(origin)
    return required


def uncovered_locations(steps, outline_steps, reviewed_branch_locations):
    for origin, step in steps.items():
        reviewed = outline_steps.get(origin, {})
        for key in ("statusLocation", "actionLocation"):
            if step.get(key) is not None and key not in reviewed:
                yield f"Checkpoint '{origin}' needs an assertion for {key} in the source outline."
        for branch in step.get("branches", []):
            location = branch.get("actionLocation")
            if location is None:
                continue
            claim = (origin, branch["to"], branch.get("condition"), location)
            if claim not in reviewed_branch_locations:
                yield (
                    f"Transition '{origin}' -> '{branch['to']}' ({branch['label']!r}) needs a matching "
                    "actionLocation assertion for its condition in the source outline."
                )


def check_outline(journey, outline, *, require_review_coverage=False):
    if not isinstance(outline, dict) or not isinstance(outline.get("routes"), list):
        raise ValueError("Source outline needs steps and routes lists")
    required = records(outline.get("steps"), "outline.steps")
    if not required:
        raise ValueError("Source outline needs at least one checkpoint")
    steps = {step["id"]: step for step in journey["steps"]}
    mismatches = []
    complete_routes = {}
    reviewed_branch_locations = set()
    step_fields = {"actor": str, "record": str, "statusLocation": str, "actionLocation": str,
                   "continuationUnknown": bool, "assignees": list, "routesComplete": bool}
    for identifier, item in required.items():
        expected = outline_expectations(item, ("id",), step_fields, f"outline.steps.{identifier}")
        if expected.pop("routesComplete", False):
            complete_routes[identifier] = []
        step = steps.get(identifier)
        if step is None:
            mismatches.append(f"Missing checkpoint '{identifier}' ({item['source']})")
            continue
        for key, value in expected.items():
            if key == "assignees":
                actual = sorted({assignment["role"] for assignment in step.get("assignments", [])})
            else:
                actual = step.get(key, False if key == "continuationUnknown" else None)
            if actual != value:
                mismatches.append(
                    f"Checkpoint '{identifier}' expects {key}={value!r}, found {actual!r} ({item['source']})"
                )

    route_fields = {"condition": str, "creates": str, "existingRecord": str, "handoff": bool, "actionLocation": str}
    for index, item in enumerate(outline["routes"]):
        field = f"outline.routes[{index}]"
        if not isinstance(item, dict):
            raise ValueError(f"{field} must be an object")
        expected = outline_expectations(item, ("from", "to"), route_fields, field)
        origin, destination = item.get("from"), item.get("to")
        require_reference(origin, required, f"{field}.from")
        require_reference(destination, required, f"{field}.to")
        if expected.get("actionLocation") is not None:
            reviewed_branch_locations.add((origin, destination, expected.get("condition"), expected["actionLocation"]))
        if origin in complete_routes:
            expected.setdefault("condition", None)
            complete_routes[origin].append((destination, expected))
        if origin not in steps or destination not in steps:
            continue
        candidates = [route for route in step_routes(steps[origin]) if route["to"] == destination]
        if not candidates:
            mismatches.append(f"Missing transition '{origin}' -> '{destination}' ({item['source']})")
        elif not any(matches_outline_route(route, destination, expected) for route in candidates):
            mismatches.append(f"Transition '{origin}' -> '{destination}' expects {expected!r} ({item['source']})")

    for origin, allowed in complete_routes.items():
        if origin not in steps:
            continue
        for route in step_routes(steps[origin]):
            if not any(matches_outline_route(route, destination, expected) for destination, expected in allowed):
                mismatches.append(
                    f"Unexpected transition '{origin}' -> '{route['to']}' "
                    f"({route['label']!r}, condition={route.get('condition')!r}). "
                    f"Reviewed routes: {required[origin]['source']}"
                )

    if require_review_coverage:
        for identifier in sorted(boundary_checkpoints(steps) - complete_routes.keys()):
            mismatches.append(
                f"Checkpoint '{identifier}' needs routesComplete=true in the source outline "
                "to render because a route changes records or actors."
            )
        if journey["version"] == 2:
            mismatches.extend(uncovered_locations(steps, required, reviewed_branch_locations))

    if mismatches:
        raise ValueError("Source outline mismatches:\n" + "\n".join(mismatches))


def review_routes(journey, origin_id=None):
    steps = {step["id"]: step for step in journey["steps"]}
    people = {person["id"]: person["label"] for person in journey.get("people", [])}
    locations = {source["id"]: source["location"] for source in journey["sources"]}
    if origin_id is not None:
        require_reference(origin_id, steps, "Review origin")
    origins = steps.values() if origin_id is None else [steps[origin_id]]
    for origin in origins:
        for route in step_routes(origin):
            target = steps[route["to"]]
            sender = people.get(origin.get("actor"), "Unspecified")
            receiver = people.get(target.get("actor"), "Unspecified")
            location = target.get("actionLocation", target.get("surface")) or "Unspecified"
            yield f"{origin['id']} -> {target['id']} | {route['label']}"
            yield f"  Condition: {route.get('condition') or 'Unspecified'}"
            yield f"  Actor: {sender} -> {receiver}"
            if route.get("creates"):
                yield f"  New record: {route['creates']}"
            if route.get("existingRecord"):
                yield f"  Existing record: {route['existingRecord']}"
            if "actionLocation" in route:
                yield f"  Branch action location: {route['actionLocation'] or 'Unspecified'}"
            yield f"  Receiving action: {target['action']} | Location: {location}"
            if target.get("authority"):
                yield f"  Receiving authority: {target['authority']}"
            for label, refs in (
                ("Transition", route.get("sources", [])), ("Receiving actor", target.get("actorSources", [])),
                ("Origin", origin["sources"]), ("Destination", target["sources"]),
            ):
                cited = dict.fromkeys(refs)
                citations = "; ".join(locations[ref] for ref in cited) if origin_id else ", ".join(cited)
                yield f"  {label} sources: {citations or 'Unspecified'}"


def validate_citation_ranges(sources, source_roots):
    roots = tuple(dict.fromkeys(root.resolve(strict=True) for root in source_roots))
    for root in roots:
        if not root.is_dir():
            raise ValueError(f"Source root must be a directory: {root}")
    line_counts = {}
    for source in sources:
        location = source["location"]
        citation = FILE_CITATION.fullmatch(location)
        if not citation:
            continue
        field = f"Source '{source['id']}' ({location})"
        file_name, target = citation.groups()
        path = PurePosixPath(file_name.replace("\\", "/"))
        if path.is_absolute() or not path.parts or ".." in path.parts:
            raise ValueError(f"{field} needs a relative path inside a source root")
        spans, separator, revision = target.partition(" @ ")
        if separator and not re.fullmatch(r"[0-9a-fA-F]{40}|[0-9a-fA-F]{64}", revision):
            raise ValueError(f"{field} needs a full Git object ID after @")
        ranges = []
        for span in spans.split(","):
            match = LINE_RANGE.fullmatch(span.strip())
            if not match:
                raise ValueError(f"{field} has an invalid line range: {span.strip()}")
            first, last = match.groups()
            start, end = int(first), int(last or first)
            if start < 1 or end < start:
                raise ValueError(f"{field} needs a positive, ordered line range: {span.strip()}")
            ranges.append(end)
        if not roots:
            raise ValueError(f"{field} needs --source-root to verify its line ranges")
        key = (path, revision)
        if key not in line_counts:
            try:
                line_counts[key] = citation_line_count(roots, path, revision)
            except (OSError, ValueError) as error:
                raise ValueError(f"{field}: {error}") from error
        if (end := max(ranges)) > (count := line_counts[key]):
            raise ValueError(f"{field} ends at line {end}, but the cited file has {count} lines")


def citation_line_count(roots, path, revision):
    contents = []
    for root in roots:
        if revision:
            result = subprocess.run(
                ["git", "-C", str(root), "cat-file", "blob", f"{revision}:./{path}"],
                capture_output=True, env={**os.environ, "GIT_NO_LAZY_FETCH": "1"},
            )
            if result.returncode == 0:
                contents.append(result.stdout)
        else:
            file = root.joinpath(*path.parts).resolve()
            if root in file.parents and file.is_file():
                contents.append(file.read_bytes())
    if not contents:
        raise ValueError("the cited file was not found in the supplied roots at the requested version")
    if len(contents) > 1:
        raise ValueError("the cited file matches multiple roots; supply an unambiguous source root or path")
    data = contents[0]
    return data.count(b"\n") + bool(data and not data.endswith(b"\n"))


def render(record, outline_path=None, *, source_roots=()):
    journey = read_journey(record)
    validate_citation_ranges(journey["sources"], source_roots)
    if outline_path is not None:
        outline = json.loads(outline_path.read_text(encoding="utf-8-sig"))
        check_outline(journey, outline, require_review_coverage=True)
    # Keep user-controlled text inside the inert JSON element.
    data = json.dumps(journey, allow_nan=False).replace("<", "\\u003c")
    logo = ""
    if LOGO.is_file():
        encoded_logo = base64.b64encode(LOGO.read_bytes()).decode("ascii")
        logo = (f'<img class="masthead-logo" src="data:image/png;base64,{encoded_logo}"'
                ' width="64" height="64" alt="">')
    html = TEMPLATE.read_text(encoding="utf-8")
    html = html.replace("__JOURNEY_LOGO__", logo, 1).replace("__JOURNEY_JSON__", data, 1)
    output = record.with_name("index.html")
    if output.exists():
        with output.open(encoding="utf-8-sig") as existing:
            existing.readline()
            if existing.readline().strip() != GENERATED:
                raise ValueError(f"Refusing to replace a different page at {output}")

    staged = NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n", dir=output.parent, delete=False)
    temp_path = Path(staged.name)
    try:
        with staged:
            staged.write(html)
        temp_path.replace(output)
    finally:
        temp_path.unlink(missing_ok=True)
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("record", type=Path, help="Path to journey.json. Writes index.html beside it.")
    parser.add_argument("--source-root", type=Path, action="append", default=[], metavar="DIR",
                        help="Root to resolve file line citations. Repeat for sources in distinct roots.")
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--review-routes", nargs="?", const="", metavar="STEP",
                       help="Print saved transitions without writing HTML. Pass a step ID for its full citations.")
    modes.add_argument("--check-outline", type=Path, metavar="OUTLINE",
                       help="Check a separate source outline against the saved journey without writing HTML.")
    modes.add_argument("--render-reviewed", type=Path, metavar="OUTLINE",
                       help="Require reviewed routes for record and actor changes and review all named locations.")
    args = parser.parse_args()
    try:
        if args.check_outline is not None:
            outline = json.loads(args.check_outline.read_text(encoding="utf-8-sig"))
            check_outline(read_journey(args.record), outline)
            print("Journey matches the supplied source outline.")
        elif args.review_routes is not None:
            for line in review_routes(read_journey(args.record), args.review_routes or None):
                print(line)
        else:
            print(render(args.record, args.render_reviewed, source_roots=args.source_root))
    except (ValueError, OSError) as error:
        operation = "check the source outline" if args.check_outline is not None else "render journey"
        parser.exit(1, f"Could not {operation}: {error}\n")


if __name__ == "__main__":
    main()
